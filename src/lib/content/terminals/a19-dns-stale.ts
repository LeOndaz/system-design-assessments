import type { TerminalScenario } from '../types';
import { oneOf } from '$lib/terminal/scenario';
import { err } from './a19-util';

/**
 * After moving api.shop.example to a new load balancer, the Cairo office still reaches the old one.
 * Authoritative DNS is correct (A records, TTL 300). The office resolver (10.20.0.2) cached the old
 * CNAME, published with TTL 86400 and never lowered before the cutover. Public resolvers are fine.
 * Decoy: /etc/hosts has a staging override that doesn't affect the prod name.
 */

const AUTH = 'ns1.dnsprovider.example';

function answer(server: string, name: string, type: string) {
	const header = (srv: string, ip: string) => `; <<>> DiG 9.18.28 <<>> ${name}${server ? ' @' + server : ''}\n;; global options: +cmd\n;; Got answer:\n;; ->>HEADER<<- opcode: QUERY, status: NOERROR, id: 4412\n;; flags: qr rd ra; QUERY: 1, ANSWER: 2, AUTHORITY: 0, ADDITIONAL: 1\n\n;; QUESTION SECTION:\n;${name}.\t\tIN\t${type}\n\n;; ANSWER SECTION:\n`;
	const footer = (ip: string) => `\n;; Query time: 3 msec\n;; SERVER: ${ip}#53(${ip}) (UDP)\n;; WHEN: Wed Oct 14 09:51:02 UTC 2026\n;; MSG SIZE  rcvd: 112\n`;
	if (name !== 'api.shop.example' && name !== 'api.shop.example.') {
		if (name.startsWith('staging')) return `${header(server, '')}${name}.\t300\tIN\tA\t10.30.1.15\n${footer('10.20.0.2')}`;
		return `${header(server, '')}\n;; status: NXDOMAIN\n${footer('10.20.0.2')}`;
	}
	if (server === '' || server === '10.20.0.2')
		return `${header(server, '10.20.0.2')}api.shop.example.\t71234\tIN\tCNAME\tapi-old-1384.eu-west-1.elb.example.\napi-old-1384.eu-west-1.elb.example. 60 IN\tA\t52.18.40.12\n${footer('10.20.0.2')}`;
	const ip = server === AUTH ? '198.51.100.53' : server;
	return `${header(server, ip)}api.shop.example.\t${server === AUTH ? 300 : 187}\tIN\tA\t34.240.11.7\napi.shop.example.\t${server === AUTH ? 300 : 187}\tIN\tA\t34.240.19.81\n${footer(ip)}`;
}

const scenario: TerminalScenario = {
	title: 'ssh it@cairo-office-jump',
	user: 'it',
	host: 'cairo-jump',
	cwd: '/home/it',
	motd: 'Cairo office jump host. Uses the office resolver like every laptop here.',
	task: 'Since last night\'s migration, **staff in the Cairo office still land on the old API** (old version banner), while customers and other offices are fine. Find the IP of the resolver that is serving the stale answer and `submit` it.',
	files: {
		'/etc/resolv.conf': '# Generated by NetworkManager\nsearch corp.example\nnameserver 10.20.0.2\noptions edns0 trust-ad\n',
		'/etc/hosts': '127.0.0.1 localhost\n10.30.1.15 staging-api.shop.example   # staging override (2025)\n',
		'/home/it/migration-notes.md':
			'# api cutover (Oct 13, 22:00 UTC)\n- created new LB, A records 34.240.11.7 / 34.240.19.81 (TTL 300)\n- replaced CNAME api-old-1384.eu-west-1.elb.example\n- TODO before cutover: lower old CNAME TTL from 86400 -> 300 a day ahead  (??? skipped, ran late)\n'
	},
	commands: {
		dig: (args) => {
			let server = '';
			let name = '';
			let type = 'A';
			const short = args.includes('+short');
			for (const a of args) {
				if (a.startsWith('@')) server = a.slice(1);
				else if (/^(A|AAAA|CNAME|NS|SOA|TXT|MX)$/i.test(a)) type = a.toUpperCase();
				else if (!a.startsWith('+') && !a.startsWith('-')) name = a;
			}
			if (!name) return err('usage: dig [@server] name [type] [+short]');
			if (type === 'NS') return `${name}.\t3600\tIN\tNS\t${AUTH}.\n`;
			if (args.includes('+trace')) return `.\t\t\t518400\tIN\tNS\ta.root-servers.net.\n;; Received 239 bytes from 10.20.0.2#53(10.20.0.2) in 1 ms\nexample.\t\t172800\tIN\tNS\tns.example-registry.net.\nshop.example.\t\t86400\tIN\tNS\t${AUTH}.\n${answer(AUTH, name, type).split(';; ANSWER SECTION:\n')[1].split('\n\n')[0]}\n;; Received 98 bytes from 198.51.100.53#53(${AUTH}) in 21 ms\n`;
			const full = answer(server, name, type);
			if (short) return full.split(';; ANSWER SECTION:\n')[1].split('\n\n')[0].split('\n').map((l) => l.split('\t').pop()).join('\n');
			return full;
		},
		nslookup: (args) => {
			const server = args[1] ?? '10.20.0.2';
			const r = answer(server === '10.20.0.2' ? '' : server, args[0] ?? '', 'A');
			const ips = [...r.matchAll(/IN\tA\t(\S+)/g)].map((m) => m[1]);
			return `Server:\t\t${server}\nAddress:\t${server}#53\n\nNon-authoritative answer:\n${r.includes('CNAME') ? `${args[0]}\tcanonical name = api-old-1384.eu-west-1.elb.example.\n` : ''}${ips.map((ip) => `Name:\t${args[0]}\nAddress: ${ip}`).join('\n')}`;
		},
		curl: (args) => {
			const verbose = args.includes('-v') || args.includes('-sv') || args.includes('-vs');
			const resolveFlag = args.join(' ').match(/--resolve \S+:(\d+\.\d+\.\d+\.\d+)/);
			const ip = resolveFlag ? resolveFlag[1] : '52.18.40.12';
			const body = ip === '52.18.40.12' ? '{"version":"1.31.4","node":"old-lb"}' : '{"version":"2.0.1","node":"new-lb"}';
			return (verbose ? `*   Trying ${ip}:443...\n* Connected to api.shop.example (${ip}) port 443\n> GET /version HTTP/1.1\n< HTTP/1.1 200 OK\n` : '') + body;
		}
	},
	answer: { prompt: 'resolver IP', check: oneOf('10.20.0.2'), success: 'The office resolver cached the old CNAME with TTL 86400 (71,234 s left). Flush that resolver\'s cache; next time lower the TTL a full old-TTL before cutover.' },
	hints: ['cat /etc/resolv.conf', 'dig api.shop.example', 'dig @1.1.1.1 api.shop.example', 'dig @ns1.dnsprovider.example api.shop.example'],
	solution: ['cat /etc/resolv.conf', 'dig api.shop.example', 'dig @1.1.1.1 api.shop.example +short', 'dig @ns1.dnsprovider.example api.shop.example', 'submit 10.20.0.2']
};

